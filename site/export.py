"""Export the DuckDB marts to site/data/summary.json for the static demo page.

Run it as a script (a package called `site` would clash with Python's own `site` module):
    python site/export.py --db data/warehouse/mcb.duckdb

The output validates against site/schema.json and stays under 2 MB. site/data/ is gitignored.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

import duckdb

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from forecast import baselines, evaluate, store  # noqa: E402

MAX_BYTES = 2 * 1024 * 1024
WEEKDAYS = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
ATTRIBUTION = {
    "real": [
        "Contains Traffic Signal Volume Data from the Department of Transport and Planning "
        "(Victoria), licensed under CC BY 4.0."
    ],
    "synthetic": [
        "Synthetic data generated by this repository with a fixed seed. Not real traffic."
    ],
}


def _data_label(con: duckdb.DuckDBPyConnection) -> str:
    lo, hi = con.execute("select min(source), max(source) from main.fct_volume_15min").fetchone()
    return "synthetic" if lo == hi == "synthetic" else "real"


def _top_sites(con: duckdb.DuckDBPyConnection, limit: int) -> list[dict[str, Any]]:
    rows = con.execute(
        "select site_id, sum(volume)::bigint from main.fct_volume_15min "
        "group by 1 order by 2 desc, 1 limit ?",
        [limit],
    ).fetchall()
    return [{"rank": i + 1, "site_id": s, "total_volume": int(v)} for i, (s, v) in enumerate(rows)]


def _heatmap(con: duckdb.DuckDBPyConnection) -> dict[str, Any]:
    rows = con.execute(
        "select iso_weekday, hour_of_day, avg(volume) from main.fct_volume_hourly group by 1, 2"
    ).fetchall()
    grid: list[list[float | None]] = [[None] * 24 for _ in range(7)]
    for weekday, hour, mean in rows:
        grid[weekday - 1][hour] = round(float(mean), 1)
    return {
        "weekdays": WEEKDAYS,
        "hours": list(range(24)),
        "unit": "mean vehicles per site per local hour",
        "values": grid,
    }


def _completeness(con: duckdb.DuckDBPyConnection, limit: int = 50) -> list[dict[str, Any]]:
    rows = con.execute(
        "select h.site_id, avg(h.completeness), count(*) from main.fct_detector_health h "
        "join (select site_id, sum(volume) v from main.fct_volume_15min group by 1 "
        "      order by 2 desc, 1 limit ?) t using (site_id) "
        "group by 1 order by 2, 1",
        [limit],
    ).fetchall()
    return [
        {"site_id": s, "completeness": round(float(c), 4), "detector_days": int(n)}
        for s, c, n in rows
    ]


def _forecast(
    con: duckdb.DuckDBPyConnection, top: list[dict[str, Any]], label: str, holdout_days: int = 7
) -> dict[str, Any]:
    mae_label = "simulated" if label == "synthetic" else "measured (host CPU)"
    sites: list[dict[str, Any]] = []
    for item in top:
        series = store.load_series(con, item["site_id"]).get(item["site_id"], {})
        if len(series) < 2:
            continue
        train, test, _ = evaluate.split_series(series, holdout_days)
        if not train or not test:
            continue
        errors = {name: [] for name in baselines.METHODS}
        hours: dict[datetime, dict[str, Any]] = {}
        for target in sorted(test):
            actual = test[target]
            hour = (
                target.replace(minute=0, second=0) if target.minute else target - timedelta(hours=1)
            )
            slot = hours.setdefault(
                hour, {"actual": [], "seasonal_naive": [], "trailing_mean_4w": []}
            )
            slot["actual"].append(actual)
            for name, fn in baselines.METHODS.items():
                pred = fn(train, target)
                slot[name].append(pred)
                if pred is not None:
                    errors[name].append(abs(pred - actual))
        if not any(errors.values()):
            continue

        def total(values: list[float | None]) -> float | None:
            if len(values) < 4 or any(v is None for v in values):
                return None
            return round(float(sum(values)), 1)  # type: ignore[arg-type]

        points = [
            {
                "hour_start": hour.replace(tzinfo=UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
                "actual": total(slot["actual"]),
                "seasonal_naive": total(slot["seasonal_naive"]),
                "trailing_mean_4w": total(slot["trailing_mean_4w"]),
            }
            for hour, slot in sorted(hours.items())
        ]
        sites.append(
            {
                "site_id": item["site_id"],
                "points": points,
                "mae_15min": {
                    name: round(sum(e) / len(e), 3) if e else None for name, e in errors.items()
                },
                "mae_label": mae_label,
            }
        )
        if len(sites) == 10:
            break
    if not sites:
        return {
            "available": False,
            "reason": "Not enough history for a 7-day holdout with a week of earlier data.",
            "holdout_days": holdout_days,
            "sites": [],
        }
    return {"available": True, "reason": "", "holdout_days": holdout_days, "sites": sites}


def build_summary(db_path: str, now: datetime | None = None) -> dict[str, Any]:
    con = duckdb.connect(db_path)
    try:
        label = _data_label(con)
        first, last = con.execute(
            "select min(local_date), max(local_date) from main.fct_volume_hourly"
        ).fetchone()
        top = _top_sites(con, 20)
        summary = {
            "schema_version": 1,
            "generated_at": (now or datetime.now(UTC)).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "data_label": label,
            "source": (
                "Department of Transport and Planning (Victoria), Traffic Signal Volume Data"
                if label == "real"
                else "Synthetic data from this repository (fixed seed)"
            ),
            "period": {"start": str(first), "end": str(last)},
            "attribution": ATTRIBUTION[label],
            "top_sites": top,
            "heatmap": _heatmap(con),
            "forecast": _forecast(con, top, label),
            "completeness": _completeness(con),
            "map": {
                "shown": False,
                "reason": "No site-locations file was joined, so no map is shown (decision D12).",
            },
        }
    finally:
        con.close()
    return summary


def validate(summary: dict[str, Any]) -> None:
    import jsonschema

    schema = json.loads((Path(__file__).parent / "schema.json").read_text())
    jsonschema.validate(summary, schema)


def export(db_path: str, out_dir: Path, now: datetime | None = None) -> Path:
    summary = build_summary(db_path, now)
    validate(summary)
    text = json.dumps(summary, separators=(",", ":"))
    if len(text.encode()) > MAX_BYTES:
        raise ValueError("summary.json would be larger than 2 MB")
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "summary.json"
    path.write_text(text + "\n")
    diagram = ROOT / "docs" / "media" / "architecture.svg"
    if diagram.exists():
        shutil.copyfile(diagram, out_dir / "architecture.svg")
    return path


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Write site/data/summary.json from the warehouse.")
    p.add_argument("--db", default="data/warehouse/mcb.duckdb")
    p.add_argument("--out-dir", type=Path, default=Path(__file__).parent / "data")
    a = p.parse_args(argv)
    path = export(a.db, a.out_dir)
    print(f"wrote {path} ({path.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
